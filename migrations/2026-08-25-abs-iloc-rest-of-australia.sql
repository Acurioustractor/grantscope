-- Generic matching pass: exact or parenthetical-stripped ILOC name, state-guarded,
-- unambiguous only. Dry-run found 18 matches, 0 ambiguous.
WITH iloc AS (
  SELECT *,
         CASE left(iloc_code, 1)
           WHEN '1' THEN 'NSW' WHEN '2' THEN 'VIC' WHEN '4' THEN 'SA'
           WHEN '6' THEN 'TAS' WHEN '8' THEN 'ACT' END AS state,
         upper(trim(regexp_replace(iloc_name, '\s*\(.*\)$', ''))) AS base_name
  FROM abs_iloc_overcrowding
  WHERE left(iloc_code, 1) IN ('1','2','4','6','8')
),
m AS (
  SELECT gc.id, i.iloc_code, i.iloc_name, i.occupied_dwellings, i.need_1plus,
         i.need_1plus_pct, i.persons_per_dwelling,
         count(*) OVER (PARTITION BY gc.id) AS n
  FROM goods_communities gc
  JOIN iloc i
    ON i.state = gc.state
   AND (upper(trim(i.iloc_name)) = upper(trim(gc.community_name))
     OR i.base_name = upper(trim(gc.community_name)))
  WHERE gc.state IN ('NSW','VIC','SA','TAS','ACT')
    AND gc.abs_iloc_code IS NULL
)
UPDATE goods_communities gc
SET abs_iloc_code         = m.iloc_code,
    occupied_dwellings    = m.occupied_dwellings,
    overcrowded_dwellings = m.need_1plus,
    overcrowded_pct       = m.need_1plus_pct,
    persons_per_dwelling  = m.persons_per_dwelling,
    overcrowding_source   = 'ABS Census 2021 IP DataPack I16, ILOC ' || m.iloc_code || ' (' || m.iloc_name || '); CNOS need-1+-extra-bedroom; persons/dwelling derived I02/I16 (approximate)',
    overcrowding_as_at    = '2021-08-10'
FROM m
WHERE gc.id = m.id AND m.n = 1;

