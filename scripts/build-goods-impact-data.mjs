#!/usr/bin/env node
/**
 * build-goods-impact-data.mjs — regenerate the Goods impact film's data module.
 *
 * Reads the live, sourced numbers and rewrites apps/video/src/goodsImpactData.ts so
 * the impact film re-renders itself each month with current figures. No invented
 * numbers: need/gap come from goods_communities (curated priority slice), communities
 * from goods_communities, and the physical footprint from the Goods Asset Register
 * canon (a different codebase, so carried as cited constants here).
 *
 * Run:  node --env-file=.env scripts/build-goods-impact-data.mjs
 * Then: cd apps/video && npm run render:goods
 *
 * Plan: act-infra thoughts/shared/plans/2026-05-28-goods-three-pipeline-operating-model.md
 */
import { psql } from './lib/psql.mjs';
import { writeFileSync } from 'fs';

// Current Goods Asset Register canon, checked 2026-07-25. Beds are deployed.
// Washers are Ben's manual in-community ruling, not a register-row count.
const DELIVERED = { beds: 540, washers: 22, asOf: '2026-07-25' };
const TOP_N = 8;
const OUT = new URL('../apps/video/src/goodsImpactData.ts', import.meta.url).pathname;

function main() {
  const [need] = psql(`SELECT SUM(demand_beds)::int beds, SUM(demand_washers)::int washers, COUNT(*) communities FROM goods_communities WHERE priority IN ('active','lead')`, { timeout: 120000 });
  const communities = psql(`SELECT community_name, state, demand_beds::int beds FROM goods_communities WHERE priority IN ('active','lead') AND demand_beds > 0 ORDER BY demand_beds DESC LIMIT ${TOP_N}`, { timeout: 120000 });
  const gap = { beds: Math.max(0, Number(need.beds) - DELIVERED.beds), washers: Math.max(0, Number(need.washers) - DELIVERED.washers) };
  const today = new Date().toLocaleDateString('en-CA', { timeZone: 'Australia/Brisbane' });

  // DB stores community names uppercase; title-case for display (place names, not shouting).
  const titleCase = s => String(s || '').toLowerCase().split(/\s+/).map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ');
  const commLines = communities
    .map(c => `    { name: ${JSON.stringify(titleCase(c.community_name))}, state: ${JSON.stringify(c.state || 'NT')}, beds: ${Number(c.beds)} },`)
    .join('\n');

  const ts = `// Goods impact film data. Every number is sourced. Refresh monthly.
//
// GENERATED by scripts/build-goods-impact-data.mjs. Edit that script, not this file.
//   need / gap: goods_communities priority in (active, lead) (the curated slice).
//   footprint: Goods Asset Register canon checked 2026-07-25.
//   washers: manual in-community ruling; not derived from register rows.
//   communities: goods_communities, priority in (active, lead), top by demand_beds.
//
// To refresh: node --env-file=.env scripts/build-goods-impact-data.mjs

export type GoodsImpactData = {
  generatedAt: string;
  footprintAsOf: string;
  need: { beds: number; washers: number; communities: number };
  delivered: { beds: number; washers: number };
  gap: { beds: number; washers: number };
  communities: { name: string; state: string; beds: number }[];
};

export const goodsImpactData: GoodsImpactData = {
  generatedAt: '${today}',
  footprintAsOf: '${DELIVERED.asOf}',
  need: { beds: ${Number(need.beds)}, washers: ${Number(need.washers)}, communities: ${Number(need.communities)} },
  delivered: { beds: ${DELIVERED.beds}, washers: ${DELIVERED.washers} },
  gap: { beds: ${gap.beds}, washers: ${gap.washers} },
  communities: [
${commLines}
  ],
};
`;

  writeFileSync(OUT, ts);
  console.log(`✓ Wrote ${OUT}`);
  console.log(`  need ${need.beds} beds / ${need.washers} washers · ${need.communities} communities`);
  console.log(`  delivered ${DELIVERED.beds}/${DELIVERED.washers} · gap ${gap.beds}/${gap.washers} · ${communities.length} communities listed`);
  console.log('  next: cd apps/video && npm run render:goods');
}
main();
