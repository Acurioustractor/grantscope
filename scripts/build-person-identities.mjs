#!/usr/bin/env node
/**
 * build-person-identities — populate person_identities by clustering name-keyed
 * person megamerges into distinct real identities (+ nominee-block flags).
 *
 * Reuses the validated clustering core (scripts/lib/person-cluster.mjs); the
 * gate scripts/person-disambig-probe.mjs must pass first.
 *
 * SAFE BY DEFAULT — dry-run writes NOTHING to the DB. It generates the upsert
 * SQL to scripts/sql/person-identities-insert.generated.sql for inspection.
 * Pass --apply to actually run that SQL via psql (Tier 3 — needs explicit go).
 *
 * Usage:
 *   node --env-file=.env scripts/build-person-identities.mjs                 # dry-run, >50 boards
 *   node --env-file=.env scripts/build-person-identities.mjs --min-boards=10 # wider dry-run
 *   node --env-file=.env scripts/build-person-identities.mjs --apply         # WRITE (after go)
 */
import 'dotenv/config';
import { createClient } from '@supabase/supabase-js';
import { execSync } from 'child_process';
import { writeFileSync } from 'fs';
import { makeQuery, fetchName, cluster, identityKey, esc } from './lib/person-cluster.mjs';

const args = process.argv.slice(2);
const APPLY = args.includes('--apply');
const MIN_BOARDS = +(args.find(a => a.startsWith('--min-boards='))?.split('=')[1] || 50);
const OUT_SQL = 'scripts/sql/person-identities-insert.generated.sql';

const supabase = createClient(
  process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL,
  process.env.SUPABASE_SERVICE_ROLE_KEY
);
const { q, qPaged } = makeQuery(supabase);
const fmt$ = (n) => n >= 1e6 ? `$${(n / 1e6).toFixed(2)}M` : n >= 1e3 ? `$${(n / 1e3).toFixed(0)}k` : n ? `$${n.toFixed(0)}` : '$0';

async function main() {
  console.log(`build-person-identities — ${APPLY ? '⚠️  APPLY (writes to DB)' : 'DRY-RUN (no DB writes)'}  min_boards=${MIN_BOARDS}`);

  const names = (await q(`
    SELECT person_name_normalised FROM mv_person_influence
    WHERE board_count > ${MIN_BOARDS} ORDER BY board_count DESC`)).map(r => r.person_name_normalised);
  console.log(`names to disambiguate: ${names.length}`);

  const rows = [];                 // {role_id, name, key, size, nominee, conf}
  let totalRoles = 0, totalIds = 0, nomineeBlocks = 0;
  let moneyExcluded = 0, moneyRetained = 0;  // money landing in nominee blocks vs real identities
  const samples = [];

  for (const name of names) {
    const data = await fetchName(qPaged, name);
    const res = cluster(name, data);
    totalRoles += res.comps.reduce((a, c) => a + c.roleIds.length, 0);
    totalIds += res.comps.length;
    let nb = 0;
    for (const c of res.comps) {
      const key = identityKey(name, c, res.geo);
      const money = (c.justice || 0) + (c.procurement || 0) + (c.donation || 0);
      if (c.isNominee) { nb++; nomineeBlocks++; moneyExcluded += money; } else { moneyRetained += money; }
      for (const role_id of c.roleIds) rows.push({ role_id, name, key, size: c.size, nominee: c.isNominee, conf: c.confidence });
    }
    if (samples.length < 8) samples.push({ name, boards: res.total, ids: res.comps.length, nb });
  }

  console.log(`\n── impact (dry-run) ──`);
  console.log(`  role rows mapped:      ${totalRoles}`);
  console.log(`  raw names:             ${names.length}  →  distinct identities: ${totalIds}  (×${(totalIds / names.length).toFixed(1)} expansion)`);
  console.log(`  nominee blocks found:  ${nomineeBlocks}  (excluded from individual rankings)`);
  console.log(`  money in nominee blocks (EXCLUDED): ${fmt$(moneyExcluded)}`);
  console.log(`  money on real identities (RETAINED, re-attributed): ${fmt$(moneyRetained)}`);
  console.log(`\n  top collapses:`);
  for (const s of samples) console.log(`    ${s.name.padEnd(28)} ${String(s.boards).padStart(4)} boards → ${String(s.ids).padStart(4)} ids  (${s.nb} nominee)`);

  // generate idempotent upsert SQL (always — for inspection)
  const values = rows.map(r =>
    `('${r.role_id}','${esc(r.name)}','${esc(r.key)}',${r.size},${r.nominee},'${r.conf}')`
  );
  const sql = [
    `-- generated by build-person-identities.mjs — ${rows.length} role→identity rows, min_boards=${MIN_BOARDS}`,
    `BEGIN;`,
    // only re-cluster the names we processed; leaves all other person_identities rows intact
    `DELETE FROM person_identities WHERE person_name_normalised IN (${[...new Set(rows.map(r => `'${esc(r.name)}'`))].join(',')});`,
    `INSERT INTO person_identities (role_id, person_name_normalised, identity_key, cluster_size, is_nominee_block, confidence) VALUES`,
    values.join(',\n') + ';',
    `COMMIT;`,
  ].join('\n');
  writeFileSync(OUT_SQL, sql);
  console.log(`\n  generated upsert SQL → ${OUT_SQL} (${rows.length} rows)`);

  if (!APPLY) { console.log(`\nDRY-RUN complete — nothing written to DB. Re-run with --apply to write.`); return; }

  // ---- APPLY (Tier 3) ----
  const pw = process.env.DATABASE_PASSWORD;
  if (!pw) { console.error('DATABASE_PASSWORD not set'); process.exit(1); }
  console.log(`\n⚠️  applying ${rows.length} rows via psql...`);
  execSync(`psql -h aws-0-ap-southeast-2.pooler.supabase.com -p 5432 -U "postgres.tednluwflfhxyucgwigh" -d postgres -f ${OUT_SQL}`,
    { env: { ...process.env, PGPASSWORD: pw }, stdio: 'inherit', timeout: 300000 });
  console.log(`✅ applied.`);
}

main().catch(e => { console.error(e.message); process.exit(1); });
